import assert from 'node:assert/strict';
import { playerMeetingHistory, timelineMeetings } from '../src/timeline-view.js';
const players=[{id:'p1',name:'Avery'},{id:'p2',name:'Jordan'},{id:'p3',name:'Sage'}];
const group={id:'g',meeting_type:'group',title:'Group <review>',date:'2026-11-20',attendees:['p1','p2'],note:'Group source <script>bad</script>',items:[{id:'a',player_id:'p2',text:'Only Jordan action',kind:'action'}]};
const team={id:'t',meeting_type:'team',title:'Team huddle',date:'2026-11-21',attendees:['p1','p2','p3'],note:'Team speech',items:[{id:'p',player_id:null,player_ids:['p1','p2','p3'],kind:'praise',text:'Shared praise'}]};
const individual={id:'i',meeting_type:'individual',title:'Personal follow-up',date:'2026-11-22',attendees:['p2'],note:'Follow-up',items:[]};
const render=(item,meeting)=>`<article id="record-${meeting.id}-${item.id}">${item.text}</article>`;
const meetings=[group,team,individual];
assert.deepEqual(timelineMeetings(meetings,'p1').map(m=>m.id),['t','g']);
const avery=playerMeetingHistory(meetings,'p1',players,false,render);
assert.ok(avery.includes('Group meeting'));
assert.ok(avery.includes('Team meeting'));
assert.ok(avery.includes('Group &lt;review&gt;'));
assert.ok(avery.includes('This player attended. No separate player feedback or tasks were saved'));
assert.ok(!avery.includes('Only Jordan action'));
assert.ok(avery.includes('Shared praise'));
assert.ok(avery.includes('record-t-p'));
assert.ok(!avery.includes('Personal follow-up'));
assert.ok(!avery.includes('<script>'));
assert.ok(avery.includes('&lt;script&gt;'));
const jordan=playerMeetingHistory(meetings,'p2',players,false,render);
assert.ok(jordan.includes('Individual meeting'));
assert.ok(jordan.includes('Only Jordan action'));
const privateMeeting={...group,note:'Private source',items:[{id:'s',kind:'observation',text:'Private detail',player_id:'p1',sensitive:true}]};
const hidden=playerMeetingHistory([privateMeeting],'p1',players,false,render);
assert.ok(hidden.includes('1 sensitive record hidden'));
assert.ok(!hidden.includes('Private source'));
assert.ok(!hidden.includes('Private detail'));
assert.ok(playerMeetingHistory([privateMeeting],'p1',players,true,render).includes('Private detail'));
const noteOnly={...team,id:'n',note_only:true,items:[]};
assert.ok(playerMeetingHistory([noteOnly],'p1',players,false,render).includes('Original conversation saved without extracted feedback or tasks'));
assert.ok(playerMeetingHistory([],'p1',players,false,render).includes('No saved meetings'));

assert.ok(avery.includes('data-meeting-disclosure="t"'));
assert.ok(!avery.includes('data-meeting-disclosure="t" open'));
assert.ok(avery.includes('data-prepare-meeting="t"'));
assert.ok(avery.includes('View details'));
const datedActions={...group,id:'actions',items:[{id:'a1',kind:'action',player_id:'p1',text:'Open task',completed:false,due_date:'2026-11-25'},
  {id:'a2',kind:'action',player_id:'p1',text:'Late task',completed:false,due_date:'2026-11-20'},
  {id:'a3',kind:'action',player_id:'p1',text:'Done task',completed:true,due_date:'2026-11-19'},
  {id:'a4',kind:'action',player_id:'p2',text:'Other player',completed:false,due_date:'2026-11-19'}]};
const dueHtml=playerMeetingHistory([datedActions],'p1',players,false,render,'2026-11-21');
assert.ok(dueHtml.includes('has-overdue-actions'));
assert.ok(dueHtml.includes('2 open · 1 overdue'));
const openHtml=playerMeetingHistory([{...datedActions,items:[datedActions.items[0]]}],'p1',players,false,render,'2026-11-25');
assert.ok(openHtml.includes('has-open-actions'));
assert.ok(openHtml.includes('1 open action'));
assert.ok(!openHtml.includes('has-overdue-actions'));
const doneHtml=playerMeetingHistory([{...datedActions,items:[datedActions.items[2]]}],'p1',players,false,render,'2026-11-21');
assert.ok(doneHtml.includes('has-completed-actions'));
assert.ok(doneHtml.includes('1 completed action'));
const hiddenAction=playerMeetingHistory([{...datedActions,items:[{...datedActions.items[1],sensitive:true}]}],'p1',players,false,render,'2026-11-21');
assert.ok(!hiddenAction.includes('timeline-action-status'));
