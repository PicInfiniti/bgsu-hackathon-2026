import assert from 'node:assert/strict';
import { filterMeetings, meetingListMarkup, meetingDetailMarkup } from '../src/meeting-library.js';

const players = [{id:'p1',name:'Avery <Smith>',number:4,position:'QB'}, {id:'p2',name:'Jordan',number:8,position:'DB'}];
const base = {id:'individual', title:'Footwork check-in', date:'2026-11-20', meeting_type:'individual', attendees:['p1'], note:'Practiced footwork.', items:[]};
const group = {...base,id:'group',title:'Performance <review>',date:'2026-11-26',meeting_type:'group',attendees:['p1','p2'],note:'Talk about their performance.',note_only:true};
const action = {id:'task',kind:'action',player_id:'p1',text:'Practice footwork',completed:false,sensitive:false};
const team = {...base,id:'team',title:'Full team film',date:'2026-11-21',meeting_type:'team',attendees:['p1','p2'],items:[action]};
const privateMeeting = {...base,id:'private',note:'Secret trainer details',items:[{...action,id:'secret',text:'Private task',sensitive:true}]};
const meetings = [base,group,team,privateMeeting], before = structuredClone(meetings);
const filter = options => filterMeetings(meetings,players,{today:'2026-11-21',...options});
assert.deepEqual(filter({type:'group'}).map(m=>m.id), ['group']);
assert.deepEqual(filter({period:'upcoming'}).map(m=>m.id), ['group','team']);
assert.deepEqual(new Set(filter({period:'past'}).map(m=>m.id)), new Set(['private','individual']));
assert.deepEqual(filter({start:'2026-11-21',end:'2026-11-26',player:'p2'}).map(m=>m.id), ['group','team']);
assert.equal(filter({start:'2026-11-26',end:'2026-11-20'}).length,0);
assert.deepEqual(filter({search:'performance'}).map(m=>m.id),['group']);
assert.equal(filter({search:'Jordan',type:'individual'}).length,0);
assert.equal(filter({search:'secret trainer'}).length,0);
assert.deepEqual(filter({search:'team film'}).map(m=>m.id), ['team']);
assert.equal(filter({sort:'oldest'})[0].date,'2026-11-20');
assert.equal(filter({sort:'title'})[0].id,'individual');
assert.deepEqual(meetings,before);

const list = meetingListMarkup(meetings,players,'2026-11-21');
assert.ok(list.includes('data-open-meeting="group"'));
assert.ok(list.includes('Future date'));
assert.ok(list.includes('Performance &lt;review&gt;'));
assert.ok(list.includes('Avery &lt;Smith&gt;'));
assert.ok(!list.includes('Secret trainer details'));
assert.ok(!list.includes('Private task'));
assert.ok(meetingListMarkup([],players,'2026-11-21').includes('No meetings match'));
let rendered=[];
const render = (i,m,sensitive) => { rendered.push([i.id,m.id,sensitive]); return `<article>${i.text}</article>`; };
const detail = meetingDetailMarkup(group,players,false,render);
assert.ok(detail.includes('Talk about their performance.'));
assert.ok(detail.includes('2026-11-26'));
assert.ok(detail.includes('Group meeting'));
assert.ok(detail.includes('data-open-player="p2"'));
assert.ok(detail.includes('no extracted feedback or tasks'));
assert.ok(detail.includes('Performance &lt;review&gt;'));
assert.deepEqual(rendered,[]);
assert.ok(!meetingDetailMarkup(privateMeeting,players,false,render).includes('Secret trainer details'));
assert.deepEqual(rendered,[]);
assert.ok(meetingDetailMarkup(privateMeeting,players,true,render).includes('Secret trainer details'));
assert.deepEqual(rendered,[['secret','private',true]]);
rendered=[];
const display_group={id:'shared',label:'Full team',player_ids:['p1','p2']};
const shared={...team,items:[{...action,display_group},{...action,id:'task2',player_id:'p2',display_group}]};
const sharedDetail=meetingDetailMarkup(shared,players,false,render);
assert.ok(sharedDetail.includes('2 player records'));
assert.equal(rendered.length,2);
assert.deepEqual(rendered.map(r=>r[0]),['task','task2']);
