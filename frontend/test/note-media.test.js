import assert from 'node:assert/strict';
import { fitSize, isHeic, resizePhoto } from '../src/image-utils.js';
import { inkBounds, strokeWidth } from '../src/pen-pad.js';
import { meetingDetailMarkup } from '../src/meeting-library.js';
assert.deepEqual(fitSize(3200,1600),{width:1600,height:800});
assert.deepEqual(fitSize(400,800),{width:400,height:800});
assert.ok(isHeic({name:'note.HEIC',type:''}));
await assert.rejects(resizePhoto({name:'note.jpg',type:'image/jpeg',size:9*1024*1024}),/8 MB/);
await assert.rejects(resizePhoto({name:'note.svg',type:'image/svg+xml',size:20}),/PNG or JPEG/);
assert.equal(inkBounds([]),null);
assert.equal(inkBounds([{color:'eraser',points:[[1,2]]}]),null);
assert.deepEqual(inkBounds([{color:'black',points:[[10,20],[50,70]]}],0),{x:10,y:20,width:40,height:50});
assert.ok(strokeWidth('pen',.8)>strokeWidth('pen',.2));
const meeting={id:'m1',title:'Note',date:'2026-11-21',attendees:[],meeting_type:'individual',note:'Source text',note_only:true,items:[],source_images:[{id:'img',kind:'pen'}]};
assert.ok(meetingDetailMarkup(meeting,[],false,()=>'' ).includes('/api/meetings/m1/media/img'));
const sensitive={...meeting,items:[{id:'secret',sensitive:true}]};
assert.ok(!meetingDetailMarkup(sensitive,[],false,()=>'' ).includes('/media/img'));
assert.ok(meetingDetailMarkup(sensitive,[],true,()=>'' ).includes('/media/img'));
console.log('Image resizing, input rejection, ink bounds and source-image visibility passed.');
