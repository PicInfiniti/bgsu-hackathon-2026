import assert from 'node:assert/strict';
import { groupRecords, meetingTypeLabel } from '../src/shared-groups.js';
import { actionRows } from '../src/action-board-view.js';

const meeting = {id:'m1',title:'Line <review>',meeting_type:'group',date:'2026-11-20',note:'Both players: Complete drill.'};
const display_group = {id:'g1',label:'Offensive line',player_ids:['p1','p2'],member_ids:['i1','i2']};
const base = {id:'i1',kind:'action',player_id:'p1',text:'Complete drill.',quote:meeting.note,skill:'Blocking',due_date:'2026-11-22',display_group,meeting};
const records = [base,{...base,id:'i2',player_id:'p2',completed:true}];
meeting.items=records;
const players=[{id:'p1',name:'Blair',number:76,position:'LT'},{id:'p2',name:'Reese',number:67,position:'C'}];
const options={today:'2026-11-21'};
assert.equal(groupRecords(records).length,1);
assert.equal(groupRecords(records)[0].allMembers.length,2);
assert.equal(groupRecords([{...records[0],text:'Edited drill.'},records[1]]).length,2);
assert.equal(groupRecords([records[0],{...records[1],meeting:{...meeting,id:'m2'}}]).length,2);
assert.equal(groupRecords([{...records[0],quote:'Other quote'},records[1]]).length,2);
const duplicates = [records[0],{...records[1],player_id:'p1'}];
assert.equal(groupRecords(duplicates).length,2);
assert.equal(actionRows(duplicates,duplicates,players,options).count,2);
const {rows,count}=actionRows(records,records,players,options);
assert.equal(count,1);
assert.ok(rows.includes('1 / 2 completed'));
assert.ok(rows.includes('Group meeting · Line &lt;review&gt;'));
assert.ok(rows.includes('data-item="i1"'));
assert.ok(rows.includes('data-item="i2"'));
assert.ok(rows.includes('Reopen'));
assert.ok(rows.includes('Offensive line'));
const filtered=actionRows([records[0]],records,players,options);
assert.ok(filtered.rows.includes('1 of 2 players match filters'));
assert.ok(filtered.rows.includes('1 / 2 completed'));
assert.ok(!filtered.rows.includes('data-item="i2"'));
const lone={...base,display_group:undefined};
const single=actionRows([lone],[lone],players,options);
assert.ok(single.rows.includes('Group meeting · Line &lt;review&gt;'));
assert.ok(!single.rows.includes('shared-action-members'));
assert.equal(meetingTypeLabel('team'),'Full team meeting');
